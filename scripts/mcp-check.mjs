// MCP 서버 점검: stdio로 띄워 도구 목록·호출 확인, 이어서 Streamable HTTP 확인
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { mkdirSync, mkdtempSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { createServer } from 'node:net';

const tsx = fileURLToPath(new URL('../node_modules/tsx/dist/cli.mjs', import.meta.url));
const verification = resolve('.local/verification');
mkdirSync(verification, { recursive: true });
const folder = mkdtempSync(join(verification, 'mcp-check-'));
const env = { ...process.env, NODE_ENV: 'test', RADAR_DATABASE: 'sqlite', RADAR_STORAGE_DIR: folder, RADAR_DB_PATH: join(folder, 'test.sqlite'), RADAR_APP_URL: 'http://127.0.0.1:9' };
delete env.RADAR_CONVERSATION_ID; delete env.RADAR_RUN_ID;
const c = new Client({ name: 'check', version: '0' });
await c.connect(new StdioClientTransport({ command: process.execPath, args: [tsx, 'mcp/server.ts'], env }));
const { tools } = await c.listTools();
const briefTool = tools.find(tool => tool.name === 'create_country_brief');
if (!briefTool?.inputSchema.required?.includes('country') || !briefTool.inputSchema.required.includes('system')) throw new Error('Word 요약 보고서 작성 도구 등록 실패');
console.log('stdio tools:', tools.map(t => t.name).join(', '));
const r = await c.callTool({ name: 'forecast', arguments: { country: '폴란드', system: '자주포' } });
console.log('forecast(폴란드, 자주포):', r.content[0].text.slice(0, 160).replace(/\s+/g, ' '));
const template = await c.callTool({ name: 'get_report_template', arguments: { format: 'pptx' } });
if (JSON.parse(template.content[0].text).templates[0].id !== 'ppt-country-v1') throw new Error('파워포인트 양식 조회 실패');
const briefTemplate = JSON.parse((await c.callTool({ name: 'get_report_template', arguments: { templateId: 'word-map-brief-v1' } })).content[0].text).templates[0];
if (!briefTemplate?.instructions?.includes('1~2쪽') || !briefTemplate.assets.some(asset => asset.name === 'hanwha-logo.jpg')) throw new Error('Word 요약 양식과 로고 정의 조회 실패');
const ingest = JSON.parse((await c.callTool({ name: 'list_ingest_sources', arguments: {} })).content[0].text);
if (!ingest.sources?.some(s => s.source === 'gdelt')) throw new Error('수집 출처 도구 연결 실패');
console.log('list_ingest_sources:', ingest.sources.map(s => s.source).join(', '));
await c.close();

const socket = createServer();
await new Promise(resolve => socket.listen(0, '127.0.0.1', resolve));
const port = socket.address().port;
await new Promise(resolve => socket.close(resolve));
const p = spawn(process.execPath, [tsx, 'mcp/server.ts', '--http', '--port', String(port)], { stdio: ['ignore', 'ignore', 'pipe'], env });
await new Promise(res => p.stderr.on('data', d => String(d).includes('http') && res()));
const h = new Client({ name: 'check-http', version: '0' });
await h.connect(new StreamableHTTPClientTransport(new URL(`http://localhost:${port}/mcp`)));
const httpTools = (await h.listTools()).tools;
if (!httpTools.some(tool => tool.name === 'create_country_brief')) throw new Error('HTTP 보고서 작성 도구 등록 실패');
console.log('http tools:', httpTools.length);
const rep = await h.callTool({ name: 'forecast', arguments: { country: 'Canada', system: 'ssk' } });
console.log('forecast(Canada, ssk):', rep.content[0].text.slice(0, 160).replace(/\s+/g, ' '));
const query = await h.callTool({ name: 'query_procurement', arguments: { country: 'CAN', system: 'ssk' } });
if (!JSON.parse(query.content[0].text).records.length) throw new Error('새 조달 조회 도구 연결 실패');
await h.close(); p.kill();
